import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {localRequests} from './test-api.mjs';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const require=createRequire(path.join(repo,'package.json'));
const {_electron}=require('playwright'),{expect}=require('@playwright/test');
const userData=fs.mkdtempSync(path.join(path.dirname(repo),'desktop-chrome-test-'));
const executablePath=process.argv[2];if(!executablePath)throw Error('Pass packaged executable');
const app=await _electron.launch({executablePath,env:{...process.env,BBGDDG_DESKTOP_USER_DATA_DIR:userData},timeout:60000});
try{
 const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.getByRole('heading',{name:'我的项目'}).waitFor({timeout:60000});
 const origin=new URL(page.url()).origin,api=localRequests(page,origin);
 const project=await(await api.post(origin+'/api/projects',{data:{title:'紧凑阅读验证'}})).json();
 const source=await(await api.post(`${origin}/api/projects/${project.id}/sources/upload`,{multipart:{file:{name:'阅读布局.pdf',mimeType:'application/pdf',buffer:fs.readFileSync(path.join(repo,'test/fixtures/sample.pdf'))}}})).json();
 await page.goto(`${origin}/projects/${project.id}/sources/${source.id}`);
 await page.getByRole('button',{name:'收起顶部',exact:true}).click();
 await expect(page.getByRole('button',{name:'展开顶部',exact:true})).toBeEnabled();
 const header=(await page.locator('.reader-topbar').boundingBox()).height;
 const paperTop=(await page.getByTestId('pdf-scroll-area').boundingBox()).y;
 assert.ok(header<=52,`collapsed header too tall: ${header}`);assert.ok(paperTop<=112,`reading area starts too low: ${paperTop}`);
 await expect(page.getByRole('toolbar',{name:'手写工具',exact:true})).toBeHidden();
 await page.getByRole('button',{name:'批注',exact:true}).click();
 await expect(page.getByRole('button',{name:'钢笔',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'阅读',exact:true}).click();
 await page.getByRole('button',{name:'下一页',exact:true}).click();
 await expect(page.getByTestId('page-progress')).toHaveText('第 2 页 / 共 2 页');
 const version=await app.evaluate(({app})=>app.getVersion());assert.equal(version,JSON.parse(fs.readFileSync(path.join(repo,'package.json'),'utf8')).version);
 await page.reload();await expect(page.getByRole('button',{name:'展开顶部',exact:true})).toBeEnabled();
 await expect(page.locator('[data-pdf-page="1"]')).toHaveAttribute('data-pdf-ready','true');
 await expect(page.getByRole('toolbar',{name:'手写工具',exact:true})).toBeHidden();
 await page.getByRole('button',{name:'导出标注 PDF',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'导出标注 PDF'});await expect(dialog).toBeVisible();
 assert.ok((await dialog.getByRole('button',{name:'下载 PDF 副本',exact:true}).boundingBox()).width>110);
 await page.keyboard.press('Escape');await page.getByRole('button',{name:'阅读',exact:true}).click();
 fs.mkdirSync(path.join(repo,'release/validation'),{recursive:true});
 await page.screenshot({path:path.join(repo,'release/validation/desktop-compact-reader.png')});
 assert.deepEqual(errors,[]);console.log(JSON.stringify({version,header,paperTop,annotationToggle:'passed',pageNavigation:'passed',preferenceReload:'passed',exportDialog:'passed',pageErrors:errors}));
}finally{await app.close()}
